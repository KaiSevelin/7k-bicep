/**
 * A Bicep provider for 7K.
 *
 * Its own repository, because D48 puts implementations outside the language: 7K states what the
 * topology must be and this says whether Azure Service Bus can be it.
 *
 * **Only the Topology layer is here, which is the mirror of the SQL provider.** A pipe is a queue; a
 * topic's subscribers are subscriptions; `where` is a subscription filter. A *message* is not
 * infrastructure — a template cannot hold a `decimal(18,2)` — so the Data layer is somebody else's job,
 * and a service is not infrastructure either: it is code, and what it runs on the model does not say.
 *
 * **What the model states is a literal; what it does not is a parameter.** The namespace, the location
 * and the SKU are deployment facts, so they are `param`s. Every property that comes from the model is
 * written out, so that `--check` sees drift when the model changes and a reviewer sees in the diff
 * exactly which declaration moved.
 *
 * **It generates the topology, not the deployment.** The template is what the model implies; applying
 * it to a subscription is a deliberate act, and `az deployment group what-if` is the way to see what
 * would change first. The generated `README` says so, because a template that looks ready to run is
 * how somebody deploys to the wrong place.
 */

